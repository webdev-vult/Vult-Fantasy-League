insert into public.fantasy_provider_settings (
  competition_season_id,
  provider,
  is_enabled,
  sync_mode,
  config
)
select id, data_provider, true, 'manual', '{}'::jsonb
from public.competition_seasons
on conflict (competition_season_id) do nothing;

create or replace function private.sync_provider_settings_from_season()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  insert into public.fantasy_provider_settings (
    competition_season_id,
    provider,
    is_enabled,
    sync_mode,
    schedule_cron,
    config
  ) values (
    new.id,
    new.data_provider,
    true,
    'manual',
    null,
    '{}'::jsonb
  )
  on conflict (competition_season_id) do update
  set provider = excluded.provider,
      sync_mode = case
        when excluded.provider = 'csv' then 'manual'
        else public.fantasy_provider_settings.sync_mode
      end,
      schedule_cron = case
        when excluded.provider = 'csv' then null
        else public.fantasy_provider_settings.schedule_cron
      end,
      updated_at = now();

  return new;
end;
$$;

revoke all on function private.sync_provider_settings_from_season() from public;

create trigger competition_seasons_sync_provider_settings
after insert or update of data_provider on public.competition_seasons
for each row execute function private.sync_provider_settings_from_season();

