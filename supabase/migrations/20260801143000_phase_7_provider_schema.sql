create table public.fantasy_provider_settings (
  id uuid primary key default gen_random_uuid(),
  competition_season_id uuid not null unique references public.competition_seasons(id) on delete cascade,
  provider text not null default 'mock'
    check (provider in ('mock', 'csv', 'approved_fpl', 'licensed')),
  is_enabled boolean not null default true,
  sync_mode text not null default 'manual'
    check (sync_mode in ('manual', 'scheduled')),
  schedule_cron text,
  max_attempts integer not null default 3 check (max_attempts between 1 and 10),
  request_timeout_seconds integer not null default 30
    check (request_timeout_seconds between 5 and 120),
  config jsonb not null default '{}'::jsonb,
  last_successful_sync_at timestamptz,
  last_failed_sync_at timestamptz,
  created_by uuid references public.admin_profiles(id) on delete set null,
  updated_by uuid references public.admin_profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (sync_mode <> 'scheduled' or schedule_cron is not null),
  check (provider <> 'csv' or sync_mode = 'manual')
);

create table public.provider_sync_runs (
  id uuid primary key default gen_random_uuid(),
  competition_season_id uuid not null references public.competition_seasons(id) on delete cascade,
  provider text not null
    check (provider in ('mock', 'csv', 'approved_fpl', 'licensed')),
  trigger_source text not null
    check (trigger_source in ('manual', 'csv_upload', 'scheduled', 'retry', 'system_test')),
  status text not null default 'running'
    check (status in ('queued', 'running', 'succeeded', 'partial', 'failed', 'cancelled')),
  idempotency_key text not null unique,
  parent_run_id uuid references public.provider_sync_runs(id) on delete set null,
  attempt_number integer not null default 1 check (attempt_number > 0),
  requested_by uuid references public.admin_profiles(id) on delete set null,
  source_label text,
  raw_record_count integer not null default 0 check (raw_record_count >= 0),
  accepted_record_count integer not null default 0 check (accepted_record_count >= 0),
  rejected_record_count integer not null default 0 check (rejected_record_count >= 0),
  warning_count integer not null default 0 check (warning_count >= 0),
  response_hash text,
  error_summary text,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (completed_at is null or completed_at >= started_at)
);

create table public.provider_sync_errors (
  id bigint generated by default as identity primary key,
  sync_run_id uuid not null references public.provider_sync_runs(id) on delete cascade,
  competition_season_id uuid not null references public.competition_seasons(id) on delete cascade,
  provider text not null
    check (provider in ('mock', 'csv', 'approved_fpl', 'licensed')),
  provider_entry_id text,
  external_round_id integer,
  stage text not null
    check (stage in ('configuration', 'fetch', 'parse', 'validation', 'persistence', 'schedule')),
  error_code text not null,
  message text not null,
  retriable boolean not null default false,
  attempt_number integer not null default 1 check (attempt_number > 0),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

